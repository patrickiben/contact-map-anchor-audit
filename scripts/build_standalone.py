#!/usr/bin/env python3
"""Deterministically bundle the lab for offline use; no third-party bundler."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'standalone' / 'AnchorAuditLab.html'


def build():
    html = (ROOT / 'docs/index.html').read_text()
    css = (ROOT / 'docs/style.css').read_text()
    core = (ROOT / 'docs/core.mjs').read_text()
    app = (ROOT / 'docs/app.mjs').read_text()
    core = re.sub(r'^export\s+', '', core, flags=re.MULTILINE)
    app = re.sub(r'^import\s+.*?from\s+[\'"]\./core\.mjs[\'"];\s*', '', app, count=1)
    if '</script' in (core + app).lower() or '</style' in css.lower():
        raise ValueError('A source contains a closing HTML tag that needs explicit escaping')
    data = []
    for name in ('study-summary', 'learning'):
        body = json.dumps(json.loads((ROOT / f'docs/{name}.json').read_text()), ensure_ascii=True, separators=(',', ':')).replace('<', '\\u003c')
        data.append(f'<script type="application/json" id="embedded-{name}">{body}</script>')
    stylesheet = '<link rel="stylesheet" href="./style.css">'
    module = '<script type="module" src="./app.mjs"></script>'
    if html.count(stylesheet) != 1 or html.count(module) != 1:
        raise ValueError('Expected one stylesheet and one application entry point')
    html = html.replace(stylesheet, '<style>\n' + css + '\n</style>')
    html = html.replace(module, '\n'.join(data) + '\n<script type="module">\n' + core + '\n' + app + '\n</script>')
    return '<!-- Generated by scripts/build_standalone.py; edit docs/ sources, then rebuild. -->\n' + html


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the tracked bundle differs from sources')
    args = parser.parse_args()
    expected = build()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            parser.exit(1, 'Standalone bundle is stale. Run python3 scripts/build_standalone.py\n')
        print('Standalone bundle matches source files.')
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(expected)
        print('Built standalone/AnchorAuditLab.html')


if __name__ == '__main__':
    main()
